    private void printActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_printActionPerformed
        try{
         String store = "Merida's Mini Mart POS";
       String cashier = (Session.first_name != null ? Session.first_name : "Unknown") 
                 + " " 
                 + (Session.last_name != null ? Session.last_name : "");

        SimpleDateFormat sdf = new SimpleDateFormat("MMMM dd, yyyy HH:mm");
        String printedDate = sdf.format(new Date());

        // Build report string
        StringBuilder report = new StringBuilder();
        report.append(store).append("\n");
        report.append("Daily Sales Report\n");
        report.append("Cashier: ").append(cashier).append("\n");
        report.append("Date Printed: ").append(printedDate).append("\n\n");

        // Table header
        report.append(String.format("%-8s %-30s %-12s %-10s %-20s\n",
                "SaleID", "Items", "Subtotal", "Payment", "Date"));
        report.append("-------------------------------------------------------------------------------\n");

        int maxItemLength = 30; // wrap Items after 30 chars

        for (int i = 0; i < Orders.getRowCount(); i++) {
            String saleID = Orders.getValueAt(i, 0).toString();
            String items = Orders.getValueAt(i, 1).toString();
            String subtotal = Orders.getValueAt(i, 2).toString();
            String payment = Orders.getValueAt(i, 3).toString();
            String dateVal = Orders.getValueAt(i, 4).toString();

            // Split Items into chunks
            for (int start = 0; start < items.length(); start += maxItemLength) {
                int end = Math.min(start + maxItemLength, items.length());
                String itemPart = items.substring(start, end);
                if (start == 0) {
                    // First line includes all columns
                    report.append(String.format("%-8s %-30s %-12s %-10s %-20s\n",
                            saleID, itemPart, subtotal, payment, dateVal));
                } else {
                    // Subsequent lines just continue Items
                    report.append(String.format("%-8s %-30s %-12s %-10s %-20s\n",
                            "", itemPart, "", "", ""));
                }
            }
        }

        report.append("-------------------------------------------------------------------------------\n");
        report.append(String.format("Total Orders: %s     Total Sales: ₱%s     Total Cash: ₱%s\n",
                lblTotalOrders.getText(),
                lblTotalSales.getText(),
                lblCashSales.getText()));

        // Show preview
        JTextArea textArea = new JTextArea(report.toString());
        textArea.setFont(new Font("Monospaced", Font.PLAIN, 14));
        textArea.setEditable(false);
        JScrollPane scrollPane = new JScrollPane(textArea);

        int option = JOptionPane.showOptionDialog(
                this,
                scrollPane,
                "Print Preview",
                JOptionPane.OK_CANCEL_OPTION,
                JOptionPane.INFORMATION_MESSAGE,
                null,
                new String[]{"Print", "Cancel"},
                "Print"
        );

        if (option == 0) {
            textArea.print();
        }

    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, "Print Error: " + e.getMessage());
    }


      // TODO add your handling code here:
    }//GEN-LAST:event_printActionPerformed

