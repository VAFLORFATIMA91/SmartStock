    // ===== LOAD TODAY SALES =====
    public void loadTodaySales(){

        model.setRowCount(0);

        try{

            Connection conn = config.connectDB();

            String sql = "SELECT s_id, items, subtotal, payment_type, date "
                    + "FROM tbl_sales WHERE DATE(date)=DATE('now','localtime')";

            PreparedStatement pst = conn.prepareStatement(sql);
            ResultSet rs = pst.executeQuery();

            int totalOrders = 0;
            double totalSales = 0;
            double totalCash = 0;

            while(rs.next()){

                int id = rs.getInt("s_id");
                String items = rs.getString("items");
                double subtotal = rs.getDouble("subtotal");
                String payment = rs.getString("payment_type");
                String date = rs.getString("date");

                model.addRow(new Object[]{
                    id,
                    items,
                    subtotal,
                    payment,
                    date
                });

                totalOrders++;
                totalSales += subtotal;

                if(payment.equalsIgnoreCase("Cash")){
                    totalCash += subtotal;
                }

            }

            lblTotalOrders.setText(String.valueOf(totalOrders));
            lblTotalSales.setText(String.format("%.2f", totalSales));
            lblCashSales.setText(String.format("%.2f", totalCash));

        }catch(Exception e){
            JOptionPane.showMessageDialog(this,e.getMessage());
        }

    }

    
    

