    // LOAD USER INFO
    // =========================
    private void loadUserData() {
        try {
            config con = new config();
            ResultSet rs = con.select("SELECT * FROM tbl_users WHERE id = " + id);

            if (rs.next()) {
                fname.setText(rs.getString("first_name"));
                lname.setText(rs.getString("last_name"));
                email.setText(rs.getString("email"));
                role.setSelectedItem(rs.getString("role"));
                status.setSelectedItem(rs.getString("status"));
            }

        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Failed to load user: " + e.getMessage());
        }
    }

    // =========================
    // LOAD USER PHOTO
    // =========================
    private void loadUserPhoto() {
        SwingUtilities.invokeLater(() -> {
            try {
                config con = new config();
                ResultSet rs = con.select("SELECT photo FROM tbl_users WHERE id = " + id);

                if (rs.next()) {
                    byte[] imgBytes = rs.getBytes("photo");

                    ImageIcon icon;

                    if (imgBytes != null && imgBytes.length > 0) {

                        ImageIcon original = new ImageIcon(imgBytes);

                        int width = jLabel8.getWidth();
                        int height = jLabel8.getHeight();

                        if (width <= 0 || height <= 0) {
                            width = 150;
                            height = 150;
                        }

                        Image scaled = original.getImage()
                                .getScaledInstance(width, height, Image.SCALE_SMOOTH);

                        icon = new ImageIcon(scaled);

                    } else {
                        icon = new ImageIcon(getClass().getResource("/images/user (5).png"));

                        Image scaled = icon.getImage()
                                .getScaledInstance(150, 150, Image.SCALE_SMOOTH);

                        icon = new ImageIcon(scaled);
                    }

                    jLabel8.setHorizontalAlignment(JLabel.CENTER);
                    jLabel8.setVerticalAlignment(JLabel.CENTER);
                    jLabel8.setIcon(icon);
                }

            } catch (Exception e) {
                System.out.println("Failed to load photo: " + e.getMessage());
            }
        });
    }

    


