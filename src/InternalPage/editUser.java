    private void saveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_saveActionPerformed
        String firstName = fname.getText().trim();
        String lastName = lname.getText().trim();
        String emailText = email.getText().trim();
        String roleText = role.getSelectedItem().toString();
        String statusText = status.getSelectedItem().toString();

        if (firstName.isEmpty() || lastName.isEmpty() || emailText.isEmpty()) {
            JOptionPane.showMessageDialog(this, "First Name, Last Name, and Email cannot be empty!");
            return;
        }

        try {
            config con = new config();
            String sql = "UPDATE tbl_users SET first_name='" + firstName +
            "', last_name='" + lastName +
            "', email='" + emailText +
            "', role='" + roleText +
            "', status='" + statusText + "' WHERE id=" + id;
            con.update(sql);
            JOptionPane.showMessageDialog(this, "User updated successfully!");
            // Open settings form
            manageUsers ut = new manageUsers();
            ut.setVisible(true);

            // Close editProfile form
            this.dispose();
        
        } catch (Exception ex) {
            JOptionPane.showMessageDialog(this, "Update failed: " + ex.getMessage());
        }

        // TODO add your handling code here:
    }//GEN-LAST:event_saveActionPerformed

