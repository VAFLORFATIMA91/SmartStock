    private void loadProductData() {
        String sql = "SELECT * FROM tbl_products WHERE p_id=?";

    try (java.sql.Connection conn = config.connectDB();
         java.sql.PreparedStatement pst = conn.prepareStatement(sql)) {

        pst.setInt(1, p_id);
        java.sql.ResultSet rs = pst.executeQuery();

        if (rs.next()) {
            name.setText(rs.getString("name"));
            category.setText(rs.getString("category"));
            price.setText(String.valueOf(rs.getDouble("price")));
            stock.setText(String.valueOf(rs.getInt("stock")));
            date.setText(rs.getString("date"));
        }

    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, "Error loading product: " + e.getMessage());
    }
}

