    private void saveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_saveActionPerformed
        String productName = name.getText().trim();
        String productCategory = category.getText().trim();
        String priceText = price.getText().trim();
        String stockText = stock.getText().trim();
        String productDate = date.getText().trim();

        if (productName.isEmpty() || productCategory.isEmpty() ||
            priceText.isEmpty() || stockText.isEmpty() || productDate.isEmpty()) {

            JOptionPane.showMessageDialog(this, "All fields are required!");
            return;
        }

        try {
            double priceValue = Double.parseDouble(priceText);
            int stockValue = Integer.parseInt(stockText);

            String sql = "UPDATE tbl_products SET name=?, category=?, price=?, stock=?, date=? WHERE p_id=?";

            try (java.sql.Connection conn = config.connectDB();
                java.sql.PreparedStatement pst = conn.prepareStatement(sql)) {

                pst.setString(1, productName);
                pst.setString(2, productCategory);
                pst.setDouble(3, priceValue);
                pst.setInt(4, stockValue);
                pst.setString(5, productDate);
                pst.setInt(6, p_id);

                pst.executeUpdate();
            }

            JOptionPane.showMessageDialog(this, "Product updated successfully!");
            this.dispose();

        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Price must be numeric and Stock must be whole number!");
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Update failed: " + e.getMessage());
        }

        // TODO add your handling code here:
    }//GEN-LAST:event_saveActionPerformed

